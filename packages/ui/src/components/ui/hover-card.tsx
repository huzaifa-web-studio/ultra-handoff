"use client";

/**
 * Hover card primitives in the aria-sera style.
 *
 * Why React Aria's PreviewTrigger instead of a hand written hover handler: it
 * already covers the parts that are easy to get wrong.
 *
 *   - a warmup delay, so passing the pointer over a link does not flash a card
 *   - a close delay plus a safe area between the trigger and the card, so the
 *     pointer can travel into the card without it closing
 *   - keyboard focus opens it after the same delay, and Escape closes it
 *   - long press opens it on touch screens, where there is no hover
 *   - Tab from the trigger moves into the card
 *
 * Generated by shadcn for the aria-sera style. The only adaptation is that the
 * trigger accepts a plain element, which is what Slate needs for an inline
 * link. See `notes` below.
 *
 * Usage:
 *
 *   <HoverCardTrigger>
 *     <Focusable><a href="...">...</a></Focusable>
 *     <HoverCard>...</HoverCard>
 *   </HoverCardTrigger>
 *
 * The `Focusable` wrapper adds no DOM node: it clones the anchor and forwards
 * the trigger props to it. A raw anchor is used instead of `Link` on purpose,
 * because inside a contenteditable React Aria's link press handling competes
 * with caret placement.
 *
 * Used by: features/link-previews/link-preview-card.tsx.
 */

import { cn } from "cn";
import {
	Popover as PopoverPrimitive,
	type PopoverProps as PopoverPrimitiveProps,
	PreviewTrigger as PreviewTriggerPrimitive,
	type PreviewTriggerProps,
} from "react-aria-components";

function HoverCardTrigger({ children, ...props }: PreviewTriggerProps) {
	return (
		<PreviewTriggerPrimitive data-slot="hover-card-trigger" {...props}>
			{children}
		</PreviewTriggerPrimitive>
	);
}

function HoverCard({
	className,
	placement = "bottom",
	offset = 8,
	crossOffset = 0,
	...props
}: Omit<PopoverPrimitiveProps, "className"> & {
	className?: string;
}) {
	return (
		<PopoverPrimitive
			data-slot="hover-card-content"
			placement={placement}
			offset={offset}
			crossOffset={crossOffset}
			className={cn(
				"z-50 w-96 max-w-[calc(100vw-1.5rem)] origin-(--trigger-anchor-point) overflow-hidden bg-popover text-sm text-popover-foreground shadow-md ring-1 ring-foreground/10 outline-hidden duration-100 data-entering:animate-in data-entering:fade-in-0 data-entering:zoom-in-95 data-exiting:animate-out data-exiting:fade-out-0 data-exiting:zoom-out-95 data-[placement=bottom]:slide-in-from-top-2 data-[placement=left]:slide-in-from-right-2 data-[placement=right]:slide-in-from-left-2 data-[placement=top]:slide-in-from-bottom-2 print:hidden",
				className,
			)}
			{...props}
		/>
	);
}

export { HoverCard, HoverCardTrigger };
